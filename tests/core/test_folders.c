#include "noshi_folders.h"
#include "test_util.h"
#include "noshi_tl_ids.h"

static void title_roundtrip(void) {
    noshi_arena arena;
    noshi_writer writer;
    noshi_tl_value *title = NULL, *decoded = NULL;
    noshi_send_entity sent[2];
    noshi_entity read[2];
    uint8_t count = 0;
    char urls[1] = {0};
    memset(sent, 0, sizeof(sent));
    noshi_arena_init(&arena, 1u << 20);
    sent[0].kind = sent[1].kind = NOSHI_ENTITY_CUSTOM_EMOJI;
    sent[0].offset = 1; sent[0].length = 2; sent[0].id = 123456789;
    sent[1].offset = 4; sent[1].length = 2; sent[1].id = 987654321;
    CHECK_EQ_INT(noshi_folder_title_build(&arena, "A\xF0\x9F\x98\x80Z\xF0\x9F\x98\x80", sent, 2, &title), NOSHI_OK);
    noshi_writer_init(&writer, 4096);
    CHECK_EQ_INT(noshi_tl_encode(title, &writer, NULL), NOSHI_OK);
    CHECK_EQ_INT(noshi_tl_decode_all(&arena, NULL, NOSHI_TL_REF_ANY, writer.data, writer.len, &decoded), NOSHI_OK);
    CHECK(noshi_tl_is(decoded, NOSHI_TL_ID_textWithEntities));
    noshi_entities_read(decoded, read, 2, urls, sizeof(urls), &count);
    CHECK_EQ_INT(count, 2);
    CHECK_EQ_INT(read[0].offset, 1); CHECK_EQ_INT(read[0].length, 2); CHECK(read[0].document_id == 123456789);
    CHECK_EQ_INT(read[1].offset, 4); CHECK_EQ_INT(read[1].length, 2); CHECK(read[1].document_id == 987654321);
    sent[1].offset = 5;
    CHECK_EQ_INT(noshi_folder_title_build(&arena, "A\xF0\x9F\x98\x80Z\xF0\x9F\x98\x80", sent, 2, &title), NOSHI_E_ARG);
    sent[1].id = 0;
    CHECK_EQ_INT(noshi_folder_title_build(&arena, "x", sent, 2, &title), NOSHI_E_ARG);
    CHECK_EQ_INT(noshi_folder_title_build(&arena, "plain", NULL, 0, &title), NOSHI_OK);
    CHECK_EQ_INT(noshi_tl_get(title, "entities")->u.vec.count, 0);
    noshi_writer_free(&writer);
    noshi_arena_free(&arena);
}

int main(void) {
    title_roundtrip();
    size_t offset = 2;
    CHECK(noshi_folder_shift_emoji(&offset, 2, 0, 0, 3));
    CHECK_EQ_INT(offset, 5);
    CHECK(noshi_folder_shift_emoji(&offset, 2, 7, 0, 1));
    CHECK_EQ_INT(offset, 5);
    CHECK(!noshi_folder_shift_emoji(&offset, 2, 6, 0, 1));
    CHECK(!noshi_folder_shift_emoji(&offset, 2, 4, 2, 0));
    CHECK(noshi_folder_shift_emoji(&offset, 2, 0, 2, 0));
    CHECK_EQ_INT(offset, 3);
    CHECK(!noshi_folder_shift_emoji(NULL, 2, 0, 0, 0));
    CHECK(!noshi_folder_shift_emoji(&offset, 0, 0, 0, 0));
    noshi_folder_rules rules;
    noshi_dialog_row dialog;
    noshi_peer_ref peers[2];
    memset(&rules, 0, sizeof(rules));
    memset(&dialog, 0, sizeof(dialog));
    memset(peers, 0, sizeof(peers));
    CHECK(!noshi_folder_scans_dialogs(0, 0));
    CHECK(!noshi_folder_scans_dialogs(NOSHI_FOLDER_SKIP_ARCHIVED, 0));
    CHECK(noshi_folder_scans_dialogs(NOSHI_FOLDER_GROUPS, 0));
    CHECK(noshi_folder_scans_dialogs(NOSHI_FOLDER_GROUPS, 1));
    CHECK(noshi_folder_scans_dialogs(NOSHI_FOLDER_GROUPS | NOSHI_FOLDER_SKIP_ARCHIVED, 0));
    CHECK(!noshi_folder_scans_dialogs(NOSHI_FOLDER_GROUPS | NOSHI_FOLDER_SKIP_ARCHIVED, 1));
    dialog.peer_kind = 1;
    dialog.peer_id = 42;
    dialog.kind = NOSHI_DIALOG_USER;
    CHECK(!noshi_folder_contains(NULL, &dialog));
    CHECK(!noshi_folder_contains(&rules, NULL));
    CHECK(!noshi_folder_contains(&rules, &dialog));
    rules.flags = NOSHI_FOLDER_CONTACTS;
    CHECK(!noshi_folder_contains(&rules, &dialog));
    dialog.contact = 1;
    CHECK(noshi_folder_contains(&rules, &dialog));
    dialog.contact = 0;
    dialog.saved = 1;
    CHECK(noshi_folder_contains(&rules, &dialog));
    dialog.saved = 0;
    rules.flags = NOSHI_FOLDER_NON_CONTACTS;
    CHECK(noshi_folder_contains(&rules, &dialog));
    dialog.kind = NOSHI_DIALOG_BOT;
    CHECK(!noshi_folder_contains(&rules, &dialog));
    rules.flags = NOSHI_FOLDER_BOTS;
    CHECK(noshi_folder_contains(&rules, &dialog));
    dialog.kind = NOSHI_DIALOG_GROUP;
    rules.flags = NOSHI_FOLDER_GROUPS;
    CHECK(noshi_folder_contains(&rules, &dialog));
    dialog.kind = NOSHI_DIALOG_CHANNEL;
    CHECK(!noshi_folder_contains(&rules, &dialog));
    rules.flags = NOSHI_FOLDER_CHANNELS | NOSHI_FOLDER_SKIP_READ | NOSHI_FOLDER_SKIP_MUTED;
    CHECK(!noshi_folder_contains(&rules, &dialog));
    dialog.unread_mark = 1;
    CHECK(noshi_folder_contains(&rules, &dialog));
    dialog.muted = 1;
    CHECK(!noshi_folder_contains(&rules, &dialog));
    dialog.mentions = 1;
    CHECK(noshi_folder_contains(&rules, &dialog));
    dialog.unread_mark = 0;
    CHECK(noshi_folder_contains(&rules, &dialog));
    dialog.folder_id = 1;
    rules.flags |= NOSHI_FOLDER_SKIP_ARCHIVED;
    CHECK(!noshi_folder_contains(&rules, &dialog));
    peers[0].kind = 1;
    peers[0].id = 42;
    rules.included = peers;
    rules.included_count = 1;
    CHECK(noshi_folder_contains(&rules, &dialog));
    dialog.peer_kind = 3;
    CHECK(!noshi_folder_contains(&rules, &dialog));
    peers[0].kind = 3;
    CHECK(noshi_folder_contains(&rules, &dialog));
    rules.excluded = peers;
    rules.excluded_count = 1;
    CHECK(!noshi_folder_contains(&rules, &dialog));
    rules.pinned = peers;
    rules.pinned_count = 1;
    CHECK(!noshi_folder_contains(&rules, &dialog));
    CHECK_EQ_INT(noshi_folder_pin_index(&rules, &dialog), 0);
    rules.excluded_count = 0;
    rules.included_count = 0;
    CHECK(noshi_folder_contains(&rules, &dialog));
    dialog.folder = 1;
    CHECK(!noshi_folder_contains(&rules, &dialog));
    dialog.folder = 0;
    rules.pinned_count = 0;
    CHECK(noshi_folder_pin_index(&rules, &dialog) == SIZE_MAX);
    rules.included_count = NOSHI_FOLDER_PEERS_MAX + 1;
    CHECK(!noshi_folder_contains(&rules, &dialog));
    rules.included_count = 1;
    rules.included = NULL;
    CHECK(!noshi_folder_contains(&rules, &dialog));
    rules.included = peers;
    peers[0].self = 1;
    dialog.saved = 1;
    CHECK(noshi_folder_contains(&rules, &dialog));
    dialog.saved = 0;
    CHECK(!noshi_folder_contains(&rules, &dialog));
    rules.included_count = 0;
    dialog.folder_id = 0;
    dialog.community = 1;
    rules.flags = 31;
    CHECK(noshi_folder_contains(&rules, &dialog));
    rules.flags = NOSHI_FOLDER_GROUPS;
    CHECK(!noshi_folder_contains(&rules, &dialog));
    return test_finish("test_folders");
}
